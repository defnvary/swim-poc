import { describe, expect, it } from 'vitest';

// pure renderers — no child processes run at import (11 §1); env is inert
process.env.DATABASE_URL ??= 'postgres://swim:swim@localhost:5432/swim_unit_noop';
const { renderVhostStage1, renderVhostStage2, renderPlatformVhost } = await import('../../src/services/nginx.js');
const { renderCompose } = await import('../../src/services/docker.js');
const { renderDockerfile, renderStaticNginxConf } = await import('../../src/services/deploy.js');

describe('vhost templates (09 §3)', () => {
  it('stage 1 renders byte-exact', () => {
    expect(renderVhostStage1('app.example.com')).toBe(`# generated by Swim — do not edit
server {
  listen 80;
  server_name app.example.com;

  location /.well-known/acme-challenge/ {
    root /var/www/certbot;
  }

  location / {
    default_type text/plain;
    return 200 'certificate pending - retry in a minute';
  }
}
`);
  });

  it('stage 2 app vhost renders byte-exact for (host, slug, port)', () => {
    expect(renderVhostStage2('app.example.com', 'demo', 3001)).toBe(`# generated by Swim — do not edit
server {
  listen 80;
  server_name app.example.com;

  location /.well-known/acme-challenge/ {
    root /var/www/certbot;
  }

  location / {
    return 301 https://$host$request_uri;
  }
}

server {
  listen 443 ssl;
  http2 on;
  server_name app.example.com;

  ssl_certificate /etc/letsencrypt/live/app.example.com/fullchain.pem;
  ssl_certificate_key /etc/letsencrypt/live/app.example.com/privkey.pem;

  location / {
    proxy_pass http://swim-app-demo:3001;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $connection_upgrade;
    proxy_buffering off;   # SSE-friendly default
  }
}
`);
  });

  it('stage 2 platform vhost renders byte-exact for (host, SWIM_DOMAIN)', () => {
    expect(renderPlatformVhost('swim.example.com')).toBe(`# generated by Swim — do not edit
server {
  listen 80;
  server_name swim.example.com;

  location /.well-known/acme-challenge/ {
    root /var/www/certbot;
  }

  location / {
    return 301 https://$host$request_uri;
  }
}

server {
  listen 443 ssl;
  http2 on;
  server_name swim.example.com;

  ssl_certificate /etc/letsencrypt/live/swim.example.com/fullchain.pem;
  ssl_certificate_key /etc/letsencrypt/live/swim.example.com/privkey.pem;

  client_max_body_size 10m;

  location /api/ {
    proxy_pass http://swim-api:3000;
    proxy_buffering off;   # SSE log streams
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $connection_upgrade;
  }

  location / {
    proxy_pass http://swim-api:3000;
  }
}
`);
  });

  it('render is deterministic — the same inputs give byte-identical output', () => {
    const a = renderVhostStage2('x.example.com', 'x', 3000);
    expect(renderVhostStage2('x.example.com', 'x', 3000)).toBe(a);
    expect(renderVhostStage1('x.example.com')).not.toBe(a); // stage differs
  });
});

describe('compose.yaml template (07 §4.3)', () => {
  const base = { slug: 'demo', sha8: 'deadbeef', port: 3000, healthcheckPath: '/healthz' } as const;

  it('renders byte-exact for generated builds (node)', () => {
    expect(renderCompose({ ...base, buildType: 'node' })).toBe(`# generated by Swim — do not edit
services:
  app:
    image: swim/demo:deadbeef
    build:
      context: .
      dockerfile: Dockerfile.swim
    container_name: swim-app-demo
    restart: unless-stopped
    env_file: .env
    networks:
      - swim-edge
    healthcheck:
      test: ["CMD-SHELL", "curl -fsS http://127.0.0.1:3000/healthz >/dev/null 2>&1 || wget -q --spider http://127.0.0.1:3000/healthz || exit 1"]
      interval: 5s
      timeout: 3s
      retries: 3
      start_period: 10s

networks:
  swim-edge:
    external: true
`);
  });

  it('renders the repo-provided Dockerfile variant', () => {
    expect(renderCompose({ ...base, buildType: 'dockerfile' })).toBe(`# generated by Swim — do not edit
services:
  app:
    image: swim/demo:deadbeef
    build:
      context: ./src
      dockerfile: Dockerfile
    container_name: swim-app-demo
    restart: unless-stopped
    env_file: .env
    networks:
      - swim-edge
    healthcheck:
      test: ["CMD-SHELL", "curl -fsS http://127.0.0.1:3000/healthz >/dev/null 2>&1 || wget -q --spider http://127.0.0.1:3000/healthz || exit 1"]
      interval: 5s
      timeout: 3s
      retries: 3
      start_period: 10s

networks:
  swim-edge:
    external: true
`);
  });
});

describe('generated Dockerfiles (07 §4.2)', () => {
  it('node template renders byte-exact', () => {
    expect(renderDockerfile('node', 3000)).toBe(`# generated by Swim — do not edit
FROM node:24-alpine
WORKDIR /app
COPY src/package*.json ./
RUN npm ci
COPY src/ ./
RUN npm run build --if-present
ENV NODE_ENV=production
USER node
EXPOSE 3000
CMD ["npm", "start"]
`);
  });

  it('static template + .swim/nginx.conf render byte-exact', () => {
    expect(renderDockerfile('static', 8080)).toBe(`# generated by Swim — do not edit
FROM nginx:1-alpine
COPY src/ /usr/share/nginx/html
COPY .swim/nginx.conf /etc/nginx/conf.d/default.conf
EXPOSE 8080
`);
    expect(renderStaticNginxConf(8080)).toBe(`# generated by Swim — do not edit
server {
  listen 8080;
  root /usr/share/nginx/html;
  index index.html;
  location / {
    try_files $uri $uri/ /index.html;
  }
}
`);
  });

  it('renderers are deterministic (regeneration is a no-op, 09 §3)', () => {
    expect(renderDockerfile('node', 3001)).toBe(renderDockerfile('node', 3001));
    expect(renderStaticNginxConf(80)).toBe(renderStaticNginxConf(80));
  });
});
