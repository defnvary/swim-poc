import { mkdir, rename, unlink, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pino } from 'pino';
import { config } from '../config.js';
import { reloadNginx } from './docker.js';

// One vhost file per Domain row, written to the swim-conf volume (09 §1).
// All templates are deterministic functions of (host, slug, port, SWIM_DOMAIN) —
// reconciliation depends on byte-identical regeneration (09 §3, 07 §10).

const log = pino({ level: 'info' });
const NGINX_DIR = join(config.dataDir, 'nginx');

const acmeLocation = `  location /.well-known/acme-challenge/ {
    root /var/www/certbot;
  }`;

export const renderVhostStage1 = (host: string): string => `# generated by Swim — do not edit
server {
  listen 80;
  server_name ${host};

${acmeLocation}

  location / {
    default_type text/plain;
    return 200 'certificate pending - retry in a minute';
  }
}
`;

const redirectServer = (host: string): string => `server {
  listen 80;
  server_name ${host};

${acmeLocation}

  location / {
    return 301 https://$host$request_uri;
  }
}`;

const tlsHeader = (host: string): string => `  listen 443 ssl;
  http2 on;
  server_name ${host};

  ssl_certificate /etc/letsencrypt/live/${host}/fullchain.pem;
  ssl_certificate_key /etc/letsencrypt/live/${host}/privkey.pem;`;

const websockets = `    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $connection_upgrade;
    proxy_buffering off;   # SSE-friendly default`;

// App hosts proxy to swim-app-<slug>:<port> (09 §3.2)
export const renderVhostStage2 = (host: string, slug: string, port: number): string =>
  `# generated by Swim — do not edit
${redirectServer(host)}

server {
${tlsHeader(host)}

  location / {
    proxy_pass http://swim-app-${slug}:${port};
${websockets}
  }
}
`;

// Platform host (swim.<SWIM_DOMAIN>) proxies to swim-api:3000 (09 §3.2)
export const renderPlatformVhost = (host: string): string =>
  `# generated by Swim — do not edit
${redirectServer(host)}

server {
${tlsHeader(host)}

  client_max_body_size 10m;

  location /api/ {
    proxy_pass http://swim-api:3000;
    proxy_buffering off;   # SSE log streams
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $connection_upgrade;
  }

  location / {
    proxy_pass http://swim-api:3000;
  }
}
`;

// Reload protocol (09 §4): the stage is a function of cert status; slug/port
// only matter for stage 2, so they are optional here.
export const renderVhost = (host: string, certIssued: boolean, slug?: string, port?: number): string =>
  certIssued
    ? renderVhostStage2(host, slug ?? '', port ?? 0)
    : renderVhostStage1(host);

// 09 §4 step 1: write <host>.conf.tmp then rename() — atomic replace
export const writeVhost = async (host: string, content: string): Promise<void> => {
  await mkdir(NGINX_DIR, { recursive: true });
  await writeFileAtomic(join(NGINX_DIR, `${host}.conf`), content);
};

// The full §4 sequence for a change: write → nginx -t (delete the offending file
// on failure, previous config keeps running) → reload.
export const writeVhostAndReload = async (host: string, content: string): Promise<void> => {
  await writeVhost(host, content);
  const test = await reloadNginx(['nginx', '-t']);
  if (test.code !== 0) {
    await removeVhost(host);
    log.error(`nginx config test failed for ${host}`);
    return;
  }
  await reloadNginx(['nginx', '-s', 'reload']);
};

const writeFileAtomic = async (target: string, content: string): Promise<void> => {
  const tmp = `${target}.tmp`;
  await writeFile(tmp, content, 'utf8');
  await rename(tmp, target);
};

export const removeVhost = async (host: string): Promise<void> => {
  await unlink(join(NGINX_DIR, `${host}.conf`)).catch(() => undefined); // idempotent (03 §6.8)
};

// Teardown: one reload for the whole batch (09 §4)
export const removeVhosts = async (hosts: string[]): Promise<void> => {
  await Promise.all(hosts.map(removeVhost));
  if (hosts.length > 0) await reload();
};

// 09 §4: nginx -t must pass before the reload is issued
export const reload = async (): Promise<void> => {
  const test = await reloadNginx(['nginx', '-t']);
  if (test.code !== 0) throw new Error('nginx config test failed');
  await reloadNginx(['nginx', '-s', 'reload']);
};

export const platformHost = (): string => `swim.${config.swimDomain ?? 'swim.local'}`;
